static const GlyphPicture* font_find(char character)
{
    if (character >= 'a' && character <= 'z')
    {
        character = static_cast<char>(character - 'a' + 'A');
    }
    for (size_t i = 0; i < sizeof(GLYPHS) / sizeof(GLYPHS[0]); i++)
    {
        if (GLYPHS[i].character == character)
        {
            return &GLYPHS[i];
        }
    }
    return nullptr;
}

void font_draw_text(const Canvas* canvas, int32_t x, int32_t y, const char* text, uint32_t color, int32_t scale)
{
    int32_t pen_x = x;
    for (const char* c = text; *c != '\0'; c++)
    {
        const GlyphPicture* glyph = font_find(*c);
        if (glyph != nullptr)
        {
            for (int32_t row = 0; row < FONT_GLYPH_HEIGHT; row++)
            {
                for (int32_t column = 0; column < FONT_GLYPH_WIDTH; column++)
                {
                    if (glyph->rows[row][column] == '#')
                    {
                        canvas_fill_rect(canvas, pen_x + column * scale, y + row * scale, scale, scale, color);
                    }
                }
            }
        }
        pen_x += FONT_ADVANCE * scale;
    }
}

int32_t font_text_width(const char* text, int32_t scale)
{
    int32_t count = 0;
    for (const char* c = text; *c != '\0'; c++)
    {
        count++;
    }
    if (count == 0)
    {
        return 0;
    }
    return (count * FONT_ADVANCE - 1) * scale;
}
